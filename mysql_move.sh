#!/bin/bash

# Скрипт автоматического переноса datadir MySQL/Percona в /home/mysql
# с использованием BIND-монтирования для сохранения уровня безопасности SELinux и Systemd.
# Запускать строго от пользователя root (или через sudo).

set -e  # Остановить выполнение при любой ошибке

SRC="/var/lib/mysql"
DST="/home/mysql"
FSTAB="/etc/fstab"

echo "=== Шаг 1: Проверка условий ==="
if [ "$EUID" -ne 0 ]; then
    echo "Ошибка: Этот скрипт должен быть запущен от имени root."
    exit 1
fi

if [ ! -d "$SRC" ]; then
    echo "Ошибка: Исходная директория $SRC не найдена."
    exit 1
fi

if [ -d "$DST" ] && [ "$(ls -A $DST 2>/dev/null)" ]; then
    echo "Ошибка: Целевая директория $DST уже существует и не пуста."
    echo "Откат: Очистите $DST или перенесите данные вручную."
    exit 1
fi

echo "=== Шаг 2: Остановка службы MySQL/Percona ==="
# Пытаемся остановить возможные вариации имени службы
systemctl stop mysql 2>/dev/null || systemctl stop mysqld 2>/dev/null || systemctl stop mariadb 2>/dev/null
echo "Служба успешно остановлена."

echo "=== Шаг 3: Перенос данных ==="
# Создаем целевую директорию, если её нет
mkdir -p "$DST"

# Копируем данные с сохранением всех прав, владельцев и расширенных атрибутов (включая SELinux-метки)
echo "Копирование файлов из $SRC в $DST... Это может занять время."
cp -a "$SRC/." "$DST/"

# На всякий случай жестко корректируем владельца на новом месте
chown -R mysql:mysql "$DST"
chmod 750 "$DST"

# Очищаем старую директорию, чтобы она стала пустой точкой монтирования
echo "Очистка исходной директории $SRC под точку монтирования..."
rm -rf "${SRC:?}"/*

echo "=== Шаг 4: Настройка постоянного монтирования (fstab) ==="
# Проверяем, нет ли уже такого монтирования в fstab
if grep -q "$DST" "$FSTAB" && grep -q "$SRC" "$FSTAB"; then
    echo "Запись в $FSTAB уже существует."
else
    echo "Добавление записи bind-mount в $FSTAB..."
    echo -e "${DST}\t${SRC}\tnone\tbind\t0 0" >> "$FSTAB"
fi

# Монтируем файловую систему
echo "Выполнение монтирования..."
mount -a

# Проверка, что монтирование прошло успешно
if ! mountpoint -q "$SRC"; then
    echo "Ошибка: Не удалось примонтировать $DST в $SRC."
    exit 1
fi
echo "Директория успешно примонтирована."

echo "=== Шаг 5: Сброс и применение политик SELinux ==="
# Нам нужно убедиться, что SELinux доверяет обоим путям.
# Задаем правила для физического пути в /home
if ! semanage fcontext -l | grep -q "$DST"; then
    echo "Регистрация нового пути в правилах SELinux..."
    semanage fcontext -a -t mysqld_db_t "${DST}(/.*)?"
fi

# Принудительно восстанавливаем стандартный контекст на точке монтирования
echo "Восстановление контекста безопасности SELinux..."
restorecon -R -v "$SRC"

echo "=== Шаг 6: Запуск службы ==="
# Перезагружаем systemd на случай, если менялись кастомные юнит-файлы
systemctl daemon-reload

# Запускаем службу обратно
if systemctl start mysql 2>/dev/null || systemctl start mysqld 2>/dev/null; then
    echo "=========================================================="
    echo "УСПЕШНО! MySQL запущен."
    echo "Данные физически находятся в: $DST"
    echo "Доступны через стандартный путь: $SRC"
    echo "Параметр ProtectHome=true остался в безопасности!"
    echo "=========================================================="
else
    echo "Ошибка при старте службы. Проверьте логи: journalctl -xeu mysql"
    exit 1
fi
